# %matplotlib inline
import os
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import statsmodels.api as sm
from scipy import stats
from statsmodels.stats.outliers_influence import variance_inflation_factor
from statsmodels.stats.diagnostic import het_breuschpagan
from sklearn.model_selection import train_test_split, KFold, cross_val_predict
from sklearn.linear_model import LinearRegression
from sklearn.metrics import r2_score, mean_squared_error, mean_absolute_error

# ---------- 1. LOAD DATA ----------
FILE = "/content/drive/MyDrive/HIT140_Final_dataset_Assessment-3_group-20.csv"
if not os.path.exists(FILE):                       # ask for upload if file isn't in Colab yet
    from google.colab import files
    files.upload()
df = pd.read_csv(FILE)
print("Shape:", df.shape, "| Missing values:", df.isna().sum().sum())

TARGET = "goal_diff"
FEATURES = ["rank_diff", "log_value_diff", "age_diff", "host_diff",
            "is_knockout", "prior_ppg_diff", "prior_gd_diff", "rest_days_diff"]
assert (df["goals_A"] - df["goals_B"] == df[TARGET]).all()   # data check

# ---------- 2. EDA ----------
print("\n=== Descriptive statistics ===")
print(df[FEATURES + [TARGET]].describe().T.round(3))

corr = df[FEATURES + [TARGET]].corr()
print("\n=== Correlation with goal_diff ===")
print(corr[TARGET].drop(TARGET).sort_values().round(3))

Xc = sm.add_constant(df[FEATURES])
vif = pd.Series([variance_inflation_factor(Xc.values, i) for i in range(1, Xc.shape[1])],
                index=FEATURES).round(2)
print("\n=== VIF (multicollinearity) ===")
print(vif)

# Figure 1: distribution + correlation heatmap
fig, ax = plt.subplots(1, 2, figsize=(10, 3.6))
sns.histplot(df[TARGET], discrete=True, ax=ax[0], color="steelblue")
ax[0].set_title("Distribution of goal difference")
ax[0].set_xlabel("goal_diff (A - B)")
sns.heatmap(corr, annot=True, fmt=".2f", cmap="coolwarm", center=0,
            annot_kws={"size": 6}, cbar=False, ax=ax[1])
ax[1].set_title("Correlation matrix")
ax[1].tick_params(labelsize=6)
plt.tight_layout()
plt.savefig("fig1_eda.png", dpi=200)
plt.show()

# ---------- 3. FULL OLS MODEL ----------
ols = sm.OLS(df[TARGET], Xc).fit()
print("\n=== OLS regression summary ===")
print(ols.summary())

# ---------- 4. PREDICTIVE EVALUATION ----------
rmse = lambda a, b: np.sqrt(mean_squared_error(a, b))

# 4a. 80/20 hold-out
X_tr, X_te, y_tr, y_te = train_test_split(df[FEATURES], df[TARGET],
                                          test_size=0.2, random_state=42)
lr = LinearRegression().fit(X_tr, y_tr)
pred_tr, pred_te = lr.predict(X_tr), lr.predict(X_te)
print("\n=== Evaluation ===")
print(f"Train  R2={r2_score(y_tr, pred_tr):.3f}  RMSE={rmse(y_tr, pred_tr):.3f}  MAE={mean_absolute_error(y_tr, pred_tr):.3f}")
print(f"Test   R2={r2_score(y_te, pred_te):.3f}  RMSE={rmse(y_te, pred_te):.3f}  MAE={mean_absolute_error(y_te, pred_te):.3f}")

# 4b. 5-fold cross-validation
cv_pred = cross_val_predict(LinearRegression(), df[FEATURES], df[TARGET],
                            cv=KFold(5, shuffle=True, random_state=42))
print(f"5-fold CV  R2={r2_score(df[TARGET], cv_pred):.3f}  RMSE={rmse(df[TARGET], cv_pred):.3f}  MAE={mean_absolute_error(df[TARGET], cv_pred):.3f}")

# 4c. baseline (always predict training mean)
base = np.full(len(y_te), y_tr.mean())
print(f"Baseline (mean) test RMSE={rmse(y_te, base):.3f}")

# ---------- 5. ASSUMPTION TESTS ----------
bp = het_breuschpagan(ols.resid, Xc)
print("\n=== Assumption checks ===")
print(f"Shapiro-Wilk p={stats.shapiro(ols.resid)[1]:.3f} | Breusch-Pagan p={bp[1]:.3f} | Durbin-Watson={sm.stats.durbin_watson(ols.resid):.2f}")

# Figure 2: actual vs predicted, residuals vs fitted, Q-Q
fig, ax = plt.subplots(1, 3, figsize=(12, 3.5))
ax[0].scatter(y_te, pred_te, c="steelblue")
lims = [min(y_te.min(), pred_te.min()) - 0.5, max(y_te.max(), pred_te.max()) + 0.5]
ax[0].plot(lims, lims, "r--")
ax[0].set_xlabel("Actual goal_diff (test)")
ax[0].set_ylabel("Predicted")
ax[0].set_title("Actual vs predicted")

ax[1].scatter(ols.fittedvalues, ols.resid, c="steelblue")
ax[1].axhline(0, color="r", ls="--")
ax[1].set_xlabel("Fitted")
ax[1].set_ylabel("Residual")
ax[1].set_title("Residuals vs fitted")

stats.probplot(ols.resid, dist="norm", plot=ax[2])
ax[2].set_title("Normal Q-Q")
plt.tight_layout()
plt.savefig("fig2_diagnostics.png", dpi=200)
plt.show()

# ---------- 6. Figure 3: coefficients with 95% CI ----------
ci = ols.conf_int().drop("const")
co = ols.params.drop("const")
fig, ax = plt.subplots(figsize=(5.5, 3.2))
ax.errorbar(co, range(len(co)), xerr=[co - ci[0], ci[1] - co],
            fmt="o", color="steelblue", capsize=3)
ax.axvline(0, color="r", ls="--")
ax.set_yticks(range(len(co)))
ax.set_yticklabels(co.index, fontsize=7)
ax.set_title("Coefficients with 95% CI", fontsize=9)
plt.tight_layout()
plt.savefig("fig3_coefficients.png", dpi=200)
plt.show()

print("\nSaved: fig1_eda.png, fig2_diagnostics.png, fig3_coefficients.png")