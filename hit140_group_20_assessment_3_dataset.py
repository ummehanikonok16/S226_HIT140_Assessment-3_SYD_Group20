assert t["fifa_rank"].isna().sum() == 0, "fifa_rank is empty - upload teams_with_rank_value.csv"
t = t.set_index("team")

# ---------- 2. ONE ROW PER TEAM PER MATCH ----------
a = m[["match_id","date","team_A","goals_A","goals_B"]].rename(columns={"team_A":"team","goals_A":"gf","goals_B":"ga"})
b = m[["match_id","date","team_B","goals_B","goals_A"]].rename(columns={"team_B":"team","goals_B":"gf","goals_A":"ga"})
L = pd.concat([a, b]).sort_values(["team","date","match_id"]).reset_index(drop=True)
L["pts"] = np.select([L.gf > L.ga, L.gf == L.ga], [3, 1], 0)

# ---------- 3. FORM FROM EARLIER MATCHES ONLY ----------
g = L.groupby("team")
L["n_prev"] = g.cumcount()                       # matches played BEFORE this one
for c in ["pts", "gf", "ga"]:
    L[c + "_prev"] = g[c].cumsum() - L[c]        # totals from earlier matches only
den = L["n_prev"].replace(0, np.nan)
L["prior_ppg"]   = (L["pts_prev"] / den).fillna(0)
L["prior_gd_pg"] = (L["gf_prev"] / den - L["ga_prev"] / den).fillna(0)
L["rest"] = g["date"].diff().dt.days.fillna(7).clip(upper=7)    # first match -> 7 days

feat = L[["match_id", "team", "prior_ppg", "prior_gd_pg", "rest"]]
A = feat.rename(columns={"team":"team_A","prior_ppg":"prior_ppg_A","prior_gd_pg":"prior_gd_pg_A","rest":"rest_A"})
B = feat.rename(columns={"team":"team_B","prior_ppg":"prior_ppg_B","prior_gd_pg":"prior_gd_pg_B","rest":"rest_B"})
df = m.merge(A, on=["match_id","team_A"]).merge(B, on=["match_id","team_B"])

# ---------- 4. THE 8 EXPLANATORY VARIABLES ----------
df["rank_diff"]      = df.team_B.map(t.fifa_rank) - df.team_A.map(t.fifa_rank)
df["log_value_diff"] = np.log(df.team_A.map(t.market_value_m)) - np.log(df.team_B.map(t.market_value_m))
df["age_diff"]       = df.team_A.map(t.avg_age) - df.team_B.map(t.avg_age)
df["host_diff"]      = df.host_A - df.host_B
df["prior_ppg_diff"] = df.prior_ppg_A - df.prior_ppg_B
df["prior_gd_diff"]  = df.prior_gd_pg_A - df.prior_gd_pg_B
df["rest_days_diff"] = df.rest_A - df.rest_B

X_COLS = ["rank_diff", "log_value_diff", "age_diff", "host_diff", "is_knockout",
          "prior_ppg_diff", "prior_gd_diff", "rest_days_diff"]
keep = ["match_id", "date", "stage", "team_A", "team_B", "goals_A", "goals_B", "goal_diff"] + X_COLS
final = df[keep].sort_values("match_id").reset_index(drop=True)

